<?php

declare(strict_types=1);

namespace Lemonade\Framework\Database\Connection;

/**
 * Defines the lifecycle, execution, escaping, and atomic transaction operations of one database connection.
 */
interface ConnectionInterface
{
    /**
     * Executes a result query with bound parameters and materializes its associative rows.
     *
     * @param array<int|string, mixed> $bindings
     * @return list<array<string, mixed>>
     */
    public function select(string $sql, array $bindings = []): array;

    /**
     * Streams a result query while retaining connection ownership until the generator is exhausted.
     *
     * @param array<int|string, mixed> $bindings
     * @return \Generator<int, array<string, mixed>, void, void>
     */
    public function cursor(string $sql, array $bindings = []): \Generator;

    /**
     * Executes a data-changing statement and returns its affected row count.
     *
     * @param array<int|string, mixed> $bindings
     */
    public function statement(string $sql, array $bindings = []): int;

    /**
     * Begins a physical transaction when the connection supports it.
     */
    public function beginTransaction(): void;

    /**
     * Commits the active physical transaction.
     */
    public function commit(): void;

    /**
     * Rolls back the active physical transaction.
     */
    public function rollBack(): void;

    /**
     * Indicates whether a physical transaction is currently active on this connection.
     */
    public function inTransaction(): bool;

    /**
     * Executes the callback atomically. A call made while this connection already has an active
     * transaction reuses that outer transaction; it must not issue a second physical BEGIN.
     *
     * @template T
     * @param callable(self): T $callback
     * @return T
     */
    public function transaction(callable $callback): mixed;

    /**
     * Returns the identifier generated by the most recent insert when the driver exposes one.
     */
    public function lastInsertId(): int|string|null;

    /**
     * Returns the affected-row count reported by the most recently executed statement.
     */
    public function affectedRows(): int;

    /**
     * Re-establishes the physical connection after a recoverable disconnect.
     */
    public function reconnect(): void;

    /**
     * Releases the physical connection and associated driver resources.
     */
    public function close(): void;

    /**
     * Returns the server version reported by the active database engine.
     */
    public function serverVersion(): string;

    /**
     * Escapes a string literal according to the active connection's SQL dialect.
     */
    public function escapeString(string $value): string;
}
