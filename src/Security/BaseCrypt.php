<?php

declare(strict_types=1);

namespace Lemonade\Framework\Security;

use Random\RandomException;

/**
 * Provides bcrypt-compatible password hashing without truncating newly hashed long passwords.
 *
 * Existing native bcrypt hashes remain verifiable. New passwords exceeding bcrypt's
 * 72-byte input limit are salted, domain-separated, and pre-hashed before bcrypt is applied.
 */
final class BaseCrypt
{
    private const string ALGO = PASSWORD_BCRYPT;
    private const int COST = 10;
    private const int BCRYPT_MAX_PASSWORD_BYTES = 72;
    private const string LONG_PASSWORD_DOMAIN = "Lemonade Framework bcrypt long password v1\0";

    /**
     * Returns a random 22-character fragment compatible with bcrypt salt encoding.
     *
     * @throws RandomException When the operating system cannot provide secure random bytes.
     * @throws \RuntimeException When the generated bytes cannot be encoded as a canonical bcrypt salt.
     */
    public static function getSalt(): string
    {
        $encoded = substr(strtr(base64_encode(random_bytes(16)), '+', '.'), 0, 22);
        $lastCharacter = match ($encoded[21]) {
            'A' => '.',
            'Q' => 'O',
            'g' => 'e',
            'w' => 'u',
            default => throw new \RuntimeException('Unable to encode a canonical bcrypt salt.'),
        };

        return substr($encoded, 0, 21) . $lastCharacter;
    }

    /**
     * Returns a lowercase hexadecimal password of the requested length, normalized to at least one character.
     *
     * The operation fails closed instead of substituting a weaker source when secure randomness is unavailable.
     *
     * @throws RandomException When the operating system cannot provide secure random bytes.
     */
    public static function generateRandomPassword(int $length = 16): string
    {
        if ($length < 1) {
            $length = 1;
        }

        $bytesLength = max(1, (int) ceil($length / 2));

        return substr(bin2hex(random_bytes($bytesLength)), 0, $length);
    }

    /**
     * Hashes a password with bcrypt using the supplied cost or the framework compatibility default.
     *
     * Inputs longer than bcrypt's 72-byte limit, or containing a NUL byte, are first
     * reduced to a salted, domain-separated SHA-384 value encoded as 64 ASCII characters.
     * Short-password hashes retain the existing native bcrypt behavior and format.
     *
     * @throws \ValueError When the selected bcrypt cost is outside the supported range.
     * @throws \RuntimeException When the runtime cannot create a valid bcrypt hash.
     */
    public static function encPassword(string $password, ?int $cost = null): string
    {
        $cost ??= self::COST;

        if (!self::requiresPreHash($password)) {
            return password_hash($password, self::ALGO, [
                'cost' => $cost,
            ]);
        }

        return self::hashLongPassword($password, $cost);
    }

    /**
     * Verifies current long-password hashes and existing native bcrypt hashes, including `$2a$` values.
     *
     * For passwords over 72 bytes, legacy direct bcrypt verification is attempted
     * before the long-password representation so existing hashes remain valid.
     */
    public static function checkHash(string $hash, string $password): bool
    {
        if (self::requiresPreHash($password)) {
            if (!str_contains($password, "\0") && self::verifyBcrypt($hash, $password)) {
                return true;
            }

            $salt = self::bcryptSalt($hash);
            if ($salt === null) {
                return false;
            }

            return self::verifyBcrypt($hash, self::preHash($password, $salt));
        }

        return self::verifyBcrypt($hash, $password);
    }

    /**
     * Reports whether a hash must be upgraded to the current bcrypt algorithm and cost.
     *
     * Native bcrypt hashes do not encode whether their original input exceeded 72 bytes,
     * so this method cannot identify legacy truncation and password reset remains the
     * migration boundary for such hashes.
     */
    public static function needsRehash(string $hash): bool
    {
        if (str_starts_with($hash, '$2a$')) {
            return true;
        }

        return password_needs_rehash($hash, self::ALGO, [
            'cost' => self::COST,
        ]);
    }

    private static function requiresPreHash(string $password): bool
    {
        return strlen($password) > self::BCRYPT_MAX_PASSWORD_BYTES
            || str_contains($password, "\0");
    }

    private static function hashLongPassword(string $password, int $cost): string
    {
        if ($cost < 4 || $cost > 31) {
            throw new \ValueError('Bcrypt cost must be between 4 and 31.');
        }

        $salt = self::getSalt();
        $setting = sprintf('$2y$%02d$%s', $cost, $salt);
        $hash = crypt(self::preHash($password, $salt), $setting);

        if (strlen($hash) !== 60 || !str_starts_with($hash, '$2y$')) {
            throw new \RuntimeException('Unable to create a bcrypt password hash.');
        }

        return $hash;
    }

    private static function preHash(string $password, string $salt): string
    {
        $material = self::LONG_PASSWORD_DOMAIN
            . $salt
            . "\0"
            . strlen($password)
            . "\0"
            . $password;

        return base64_encode(hash('sha384', $material, true));
    }

    private static function bcryptSalt(string $hash): ?string
    {
        if (preg_match('/^\$2[aby]\$\d{2}\$([.\/A-Za-z0-9]{22})/', $hash, $matches) !== 1) {
            return null;
        }

        return $matches[1];
    }

    private static function verifyBcrypt(string $hash, string $password): bool
    {
        if (str_starts_with($hash, '$2a$')) {
            return hash_equals($hash, crypt($password, $hash));
        }

        try {
            return password_verify($password, $hash);
        } catch (\ValueError) {
            return false;
        }
    }
}
