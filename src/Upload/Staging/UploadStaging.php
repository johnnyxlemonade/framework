<?php

declare(strict_types=1);

namespace Lemonade\Framework\Upload\Staging;

use Lemonade\Framework\Filesystem\Filesystem;
use Lemonade\Framework\Localization\TranslatorInterface;
use Lemonade\Framework\Upload\Chunk\ChunkUploadConfig;
use Lemonade\Framework\Upload\Exception\UploadStorageException;
use Lemonade\Framework\Upload\Exception\UploadValidationException;
use Lemonade\Framework\Upload\UploadPathPolicy;
use Psr\Http\Message\StreamInterface;
use Psr\Http\Message\UploadedFileInterface;

/**
 * Creates sealed upload snapshots in private writable storage while enforcing byte limits during streaming.
 *
 * @internal UploadService uses this boundary before any MIME, image, or final-storage operation.
 */
final readonly class UploadStaging
{
    private const int COPY_BYTES = 8192;
    private const int CREATE_ATTEMPTS = 10;

    private ChunkUploadConfig $cleanupConfig;

    /**
     * Retains the private path, filesystem, and translated failure boundaries used by every upload snapshot.
     */
    public function __construct(
        private TranslatorInterface $translator,
        private Filesystem $filesystem,
        private UploadPathPolicy $pathPolicy,
        ?ChunkUploadConfig $cleanupConfig = null,
    ) {
        $this->cleanupConfig = $cleanupConfig ?? new ChunkUploadConfig();
    }

    /**
     * Copies an uploaded stream exactly once and returns its measured immutable snapshot.
     *
     * The client-reported size is deliberately ignored; the byte limit is enforced before each staged write.
     *
     * @throws UploadValidationException When transport state, stream state, or actual bytes are invalid
     * @throws UploadStorageException When private staging cannot be safely created or written
     */
    public function stage(?UploadedFileInterface $file, int $maxBytes): StagedUpload
    {
        $this->cleanupOrphans();

        if ($file === null) {
            throw new UploadValidationException($this->translator->get('upload.payload_missing'));
        }

        $error = $file->getError();

        if ($error !== UPLOAD_ERR_OK) {
            throw new UploadValidationException($this->uploadErrorMessage($error));
        }

        try {
            $stream = $file->getStream();
        } catch (\Throwable $exception) {
            throw new UploadValidationException(
                $this->translator->get('upload.tmp_not_valid'),
                previous: $exception,
            );
        }

        $this->prepareStream($stream);

        return $this->writeStream(
            $stream,
            $file->getClientFilename() ?? '',
            $maxBytes,
        );
    }

    /**
     * Seals framework-generated bytes as a second private snapshot before final publication.
     *
     * @throws UploadValidationException When generated output is empty or exceeds the profile limit
     * @throws UploadStorageException When private staging cannot be safely created or written
     */
    public function stageBytes(string $contents, string $clientFilename, int $maxBytes): StagedUpload
    {
        $this->cleanupOrphans();

        $size = strlen($contents);

        if ($size === 0) {
            throw new UploadValidationException($this->translator->get('upload.file_empty'));
        }

        if ($size > $maxBytes) {
            throw new UploadValidationException($this->translator->get('upload.file_too_large'));
        }

        [$path, $handle] = $this->createSnapshotFile();
        $hash = hash_init('sha256');

        try {
            $this->writeAll($handle, $contents, $path);
            hash_update($hash, $contents);
            $this->seal($handle, $path);
        } catch (\Throwable $exception) {
            $this->closeQuietly($handle);
            $this->removeQuietly($path);

            if ($exception instanceof UploadValidationException || $exception instanceof UploadStorageException) {
                throw $exception;
            }

            throw new UploadStorageException(
                $this->translator->get('upload.move_failed'),
                previous: $exception,
            );
        }

        return new StagedUpload(
            path: $path,
            clientFilename: $clientFilename,
            sizeBytes: $size,
            sha256: hash_final($hash),
            lease: new StagedUploadLease($handle),
        );
    }

    /**
     * Verifies that a sealed snapshot still has its measured size and digest.
     *
     * @throws UploadStorageException When the snapshot is missing, unreadable, or unexpectedly changed
     */
    public function assertIntact(StagedUpload $upload): void
    {
        try {
            $size = $this->filesystem->size($upload->path());
            $hash = $this->filesystem->hash($upload->path(), 'sha256');
        } catch (\Throwable $exception) {
            throw new UploadStorageException(
                $this->translator->get('upload.tmp_not_valid'),
                previous: $exception,
            );
        }

        if ($size !== $upload->sizeBytes() || !hash_equals($upload->sha256(), $hash)) {
            throw new UploadStorageException($this->translator->get('upload.tmp_not_valid'));
        }
    }

    /**
     * Removes a snapshot without allowing cleanup failures to hide the primary upload outcome.
     */
    public function discard(?StagedUpload $upload): void
    {
        if (!$upload instanceof StagedUpload) {
            return;
        }

        $upload->releaseLease();
        $this->removeQuietly($upload->path());
    }

    /**
     * Reclaims a bounded number of old snapshots whose process lease is no longer active.
     *
     * Files outside the private staging root, symbolic links, recent snapshots, and locked snapshots are ignored.
     */
    public function cleanupOrphans(?int $now = null): int
    {
        $root = $this->pathPolicy->stagingRoot();

        if (!is_dir($root)) {
            return 0;
        }

        try {
            $this->pathPolicy->assertStagingRootSeparated();
            $this->pathPolicy->assertStagingDirectory($root);
        } catch (\Throwable $exception) {
            throw new UploadStorageException(
                $this->translator->get('upload.tmp_not_valid'),
                previous: $exception,
            );
        }

        $now ??= time();
        $cutoff = $now - $this->cleanupConfig->stagingOrphanTtlSeconds();
        $removed = 0;
        $examined = 0;

        try {
            foreach ($this->filesystem->tree($root, false) as $entry) {
                if (++$examined > $this->cleanupConfig->cleanupBatchSize()) {
                    break;
                }

                $path = $entry->getPathname();

                if (!$this->isOrphanCandidate($path, $cutoff)) {
                    continue;
                }

                $handle = @fopen($path, 'rb');

                if ($handle === false) {
                    continue;
                }

                try {
                    if (!@flock($handle, LOCK_EX | LOCK_NB)) {
                        continue;
                    }

                    if (!$this->openedFileMatchesPath($handle, $path) || !$this->isOrphanCandidate($path, $cutoff)) {
                        continue;
                    }

                    if (@chmod($path, 0600) && @unlink($path)) {
                        ++$removed;
                    }
                } finally {
                    @flock($handle, LOCK_UN);
                    @fclose($handle);
                }
            }
        } catch (\Throwable $exception) {
            throw new UploadStorageException(
                $this->translator->get('upload.tmp_not_valid'),
                previous: $exception,
            );
        }

        return $removed;
    }

    private function writeStream(
        StreamInterface $stream,
        string $clientFilename,
        int $maxBytes,
    ): StagedUpload {
        if ($maxBytes <= 0) {
            throw new UploadValidationException($this->translator->get('upload.file_too_large'));
        }

        [$path, $handle] = $this->createSnapshotFile();
        $hash = hash_init('sha256');
        $written = 0;

        try {
            while (true) {
                $remaining = $maxBytes - $written;
                $readBytes = min(self::COPY_BYTES, $remaining + 1);
                $chunk = $stream->read($readBytes);

                if ($chunk === '') {
                    if ($stream->eof()) {
                        break;
                    }

                    throw new UploadValidationException($this->translator->get('upload.tmp_not_valid'));
                }

                $chunkBytes = strlen($chunk);

                if ($chunkBytes > $readBytes) {
                    throw new UploadValidationException($this->translator->get('upload.tmp_not_valid'));
                }

                if ($chunkBytes > $remaining) {
                    throw new UploadValidationException($this->translator->get('upload.file_too_large'));
                }

                $this->writeAll($handle, $chunk, $path);
                hash_update($hash, $chunk);
                $written += $chunkBytes;
            }

            if ($written === 0) {
                throw new UploadValidationException($this->translator->get('upload.file_empty'));
            }

            $this->seal($handle, $path);
        } catch (\Throwable $exception) {
            $this->closeQuietly($handle);
            $this->removeQuietly($path);

            if ($exception instanceof UploadValidationException || $exception instanceof UploadStorageException) {
                throw $exception;
            }

            throw new UploadValidationException(
                $this->translator->get('upload.tmp_not_valid'),
                previous: $exception,
            );
        }

        return new StagedUpload(
            path: $path,
            clientFilename: $clientFilename,
            sizeBytes: $written,
            sha256: hash_final($hash),
            lease: new StagedUploadLease($handle),
        );
    }

    private function prepareStream(StreamInterface $stream): void
    {
        if (!$stream->isReadable()) {
            throw new UploadValidationException($this->translator->get('upload.tmp_not_valid'));
        }

        try {
            if ($stream->isSeekable()) {
                $stream->rewind();

                return;
            }

            if ($stream->tell() !== 0) {
                throw new UploadValidationException($this->translator->get('upload.tmp_not_valid'));
            }
        } catch (UploadValidationException $exception) {
            throw $exception;
        } catch (\Throwable $exception) {
            throw new UploadValidationException(
                $this->translator->get('upload.tmp_not_valid'),
                previous: $exception,
            );
        }
    }

    /**
     * @return array{string, resource}
     */
    private function createSnapshotFile(): array
    {
        $root = $this->pathPolicy->stagingRoot();

        try {
            $this->pathPolicy->assertStagingRootSeparated();
            $this->pathPolicy->assertStagingDirectory($root);
            $this->filesystem->create($root, 0700);

            if (!@chmod($root, 0700)) {
                throw new \RuntimeException('Upload staging permissions cannot be restricted.');
            }

            $this->pathPolicy->assertStagingDirectory($root);
        } catch (\Throwable $exception) {
            throw new UploadStorageException(
                $this->translator->get('upload.create_target_directory_failed', ['directory' => $root]),
                previous: $exception,
            );
        }

        $previous = null;

        for ($attempt = 0; $attempt < self::CREATE_ATTEMPTS; ++$attempt) {
            try {
                $path = $root . DIRECTORY_SEPARATOR . bin2hex(random_bytes(32)) . '.stage';
                $handle = @fopen($path, 'x+b');
            } catch (\Throwable $exception) {
                $previous = $exception;

                continue;
            }

            if ($handle === false) {
                continue;
            }

            if (!@chmod($path, 0600)) {
                $this->closeQuietly($handle);
                $this->removeQuietly($path);

                continue;
            }

            if (!@flock($handle, LOCK_SH)) {
                $this->closeQuietly($handle);
                $this->removeQuietly($path);

                continue;
            }

            return [$path, $handle];
        }

        throw new UploadStorageException(
            $this->translator->get('upload.move_failed'),
            previous: $previous,
        );
    }

    /**
     * @param resource $handle
     */
    private function writeAll($handle, string $contents, string $path): void
    {
        $length = strlen($contents);
        $offset = 0;

        while ($offset < $length) {
            $written = @fwrite($handle, substr($contents, $offset));

            if ($written === false || $written === 0) {
                throw new UploadStorageException(
                    $this->translator->get('upload.move_failed'),
                );
            }

            $offset += $written;
        }
    }

    /**
     * @param resource $handle
     */
    private function seal($handle, string $path): void
    {
        if (!@fflush($handle)) {
            throw new UploadStorageException($this->translator->get('upload.move_failed'));
        }

        if (function_exists('fsync') && !@fsync($handle)) {
            throw new UploadStorageException($this->translator->get('upload.move_failed'));
        }

        if (!@chmod($path, 0400)) {
            throw new UploadStorageException($this->translator->get('upload.move_failed'));
        }

    }

    /**
     * @param resource|null $handle
     */
    private function closeQuietly($handle): void
    {
        if (!is_resource($handle)) {
            return;
        }

        try {
            @fclose($handle);
        } catch (\Throwable) {
        }
    }

    private function removeQuietly(string $path): void
    {
        if (!is_file($path) && !is_link($path)) {
            return;
        }

        try {
            @chmod($path, 0600);
            @unlink($path);
        } catch (\Throwable) {
        }
    }

    private function uploadErrorMessage(int $code): string
    {
        return match ($code) {
            UPLOAD_ERR_INI_SIZE, UPLOAD_ERR_FORM_SIZE => $this->translator->get('upload.error_too_large'),
            UPLOAD_ERR_PARTIAL => $this->translator->get('upload.error_partial'),
            UPLOAD_ERR_NO_FILE => $this->translator->get('upload.error_no_file'),
            UPLOAD_ERR_NO_TMP_DIR => $this->translator->get('upload.error_no_tmp_dir'),
            UPLOAD_ERR_CANT_WRITE => $this->translator->get('upload.error_cant_write'),
            UPLOAD_ERR_EXTENSION => $this->translator->get('upload.error_stopped_by_extension'),
            default => $this->translator->get('upload.error_unknown'),
        };
    }

    /** @phpstan-impure */
    private function isOrphanCandidate(string $path, int $cutoff): bool
    {
        clearstatcache(true, $path);

        if (
            dirname($path) !== $this->pathPolicy->stagingRoot()
            || preg_match('/^[a-f0-9]{64}\.stage$/', basename($path)) !== 1
            || !is_file($path)
            || is_link($path)
        ) {
            return false;
        }

        $modified = @filemtime($path);

        return is_int($modified) && $modified <= $cutoff;
    }

    /**
     * @param resource $handle
     */
    private function openedFileMatchesPath($handle, string $path): bool
    {
        $opened = @fstat($handle);
        $current = @lstat($path);

        return $opened !== false
            && $current !== false
            && !is_link($path)
            && ($opened['mode'] & 0170000) === 0100000
            && $opened['dev'] === $current['dev']
            && $opened['ino'] === $current['ino'];
    }
}
